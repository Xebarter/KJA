import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/** Must match Desktop App/src/shared/ports.ts - baked into the client bundle. */
const PROXY_URL = "http://127.0.0.1:47321";

const root = resolve(fileURLToPath(new URL(".", import.meta.url)), "../..");

function readEnvFile(filePath) {
  if (!existsSync(filePath)) return {};
  const out = {};
  for (const line of readFileSync(filePath, "utf8").split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq < 0) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    out[key] = value;
  }
  return out;
}

const fileEnv = {
  ...readEnvFile(join(root, ".env")),
  ...readEnvFile(join(root, ".env.local")),
};

const upstream =
  process.env.KJA_UPSTREAM_SUPABASE_URL ||
  fileEnv.KJA_UPSTREAM_SUPABASE_URL ||
  process.env.NEXT_PUBLIC_SUPABASE_URL ||
  fileEnv.NEXT_PUBLIC_SUPABASE_URL ||
  "";

if (!upstream || upstream.includes("127.0.0.1")) {
  console.error(
    "Set NEXT_PUBLIC_SUPABASE_URL (or KJA_UPSTREAM_SUPABASE_URL) to your real Supabase project URL before packing.",
  );
  process.exit(1);
}

const anon =
  process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY ||
  fileEnv.NEXT_PUBLIC_SUPABASE_ANON_KEY ||
  process.env.SUPABASE_ANON_KEY ||
  fileEnv.SUPABASE_ANON_KEY ||
  "";
const service =
  process.env.SUPABASE_SERVICE_ROLE_KEY || fileEnv.SUPABASE_SERVICE_ROLE_KEY || "";
const site =
  process.env.KJA_SITE_URL ||
  fileEnv.KJA_SITE_URL ||
  process.env.NEXT_PUBLIC_SITE_URL ||
  fileEnv.NEXT_PUBLIC_SITE_URL ||
  "https://kja.ug";

if (!anon) {
  console.error("Set NEXT_PUBLIC_SUPABASE_ANON_KEY before packing.");
  process.exit(1);
}

// Runtime env for the Electron proxy (packaged installs have no developer .env).
const desktopDir = resolve(fileURLToPath(new URL(".", import.meta.url)), "..");
const resourcesDir = join(desktopDir, "resources");
mkdirSync(resourcesDir, { recursive: true });
const desktopEnvLines = [
  `# Generated by pack-next.mjs - do not commit.`,
  `KJA_UPSTREAM_SUPABASE_URL=${upstream}`,
  `NEXT_PUBLIC_SUPABASE_ANON_KEY=${anon}`,
  `KJA_SITE_URL=${site}`,
];
if (service) desktopEnvLines.push(`SUPABASE_SERVICE_ROLE_KEY=${service}`);
writeFileSync(join(resourcesDir, "desktop.env"), `${desktopEnvLines.join("\n")}\n`, "utf8");
console.log(`[pack-next] Wrote ${join(resourcesDir, "desktop.env")}`);

const result = spawnSync("npm", ["run", "build"], {
  cwd: root,
  env: {
    ...process.env,
    ...fileEnv,
    KJA_DESKTOP: "1",
    // Enables next.config output: 'standalone' (not used during next dev).
    KJA_DESKTOP_PACK: "1",
    // Client + server must share the loopback proxy URL in the packaged app.
    KJA_UPSTREAM_SUPABASE_URL: upstream,
    NEXT_PUBLIC_SUPABASE_URL: PROXY_URL,
  },
  stdio: "inherit",
  shell: process.platform === "win32",
});
process.exit(result.status ?? 1);
